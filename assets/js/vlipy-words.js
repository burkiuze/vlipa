/* The words for one language, with English behind them for anything a
   translation is missing and for a language somebody typed in themselves. */
export function wordsFor(language) {
  return { ...WORDS.English, ...(WORDS[language] || {}) };
}

export function sectorsFor(language) {
  const words = wordsFor(language);

  return SECTOR_KEYS.map((key) => ({
    id: key,
    emoji: SECTOR_EMOJI[key],
    label: words[key],
    note: words[`${key}Note`],
  }));
}

